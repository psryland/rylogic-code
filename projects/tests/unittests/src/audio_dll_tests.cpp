		PRUnitTestMethod(StreamPlaybackToCompletion, Extended)
		{
			auto fix = AudioFixture{};
			auto desc = MakeStreamDesc(EBus::Effects, 0);
			auto stream = StreamHandle{};
			PR_EXPECT(fix.m_api.StreamCreateOgg(fix.m_engine, &desc, k_ogg_fixture_bytes, sizeof(k_ogg_fixture_bytes), &stream) == EStatus::Success);
			PR_EXPECT(fix.m_api.StreamPlay(fix.m_engine, stream) == EStatus::Success);

			// Decode happens exclusively on the engine's background worker thread, so completion is
			// observed by polling Update() rather than expecting it synchronously after StreamPlay.
			auto reached_stopped = PollUntil(fix.m_api, fix.m_engine, [&]
				{
					auto state = StreamState{};
					PR_EXPECT(fix.m_api.StreamStateGet(fix.m_engine, stream, &state) == EStatus::Success);
					return state.playback == EPlaybackState::Stopped;
				});
			PR_EXPECT(reached_stopped);

			auto final_state = StreamState{};
			PR_EXPECT(fix.m_api.StreamStateGet(fix.m_engine, stream, &final_state) == EStatus::Success);
			PR_EXPECT(final_state.pcm_position == final_state.pcm_total);
			PR_EXPECT(final_state.underrun_count == 0);

			// A StreamStopped completion event should have been queued for this exact stream handle.
			// A zero-capacity peek reports the required count via BufferTooSmall rather than draining the queue.
			auto required = std::uint32_t{};
			PR_EXPECT(fix.m_api.EventsCopy(fix.m_engine, nullptr, 0, &required) == EStatus::BufferTooSmall);
			PR_EXPECT(required > 0);
			auto events = std::vector<Event>(required);
			PR_EXPECT(fix.m_api.EventsCopy(fix.m_engine, events.data(), static_cast<std::uint32_t>(events.size()), &required) == EStatus::Success);

			auto found_stopped = std::any_of(events.begin(), events.end(), [&](Event const& event)
				{
					return event.type == EEvent::StreamStopped && event.voice == stream && event.status == EStatus::Success;
				});
			PR_EXPECT(found_stopped);

			PR_EXPECT(fix.m_api.StreamDestroy(fix.m_engine, stream) == EStatus::Success);
		}

