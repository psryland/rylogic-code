		// Create a short valid mono PCM16 WAV file without external fixtures.
		std::vector<std::byte> MakeWave(std::uint32_t sample_count = 480)
		{
			auto data_size = sample_count * sizeof(std::int16_t);
			auto bytes = std::vector<std::byte>(44 + data_size);
			auto write = [&](std::size_t offset, auto value)
			{
				std::memcpy(bytes.data() + offset, &value, sizeof(value));
			};

			write(0, std::uint32_t{0x46464952});
			write(4, std::uint32_t{36 + static_cast<std::uint32_t>(data_size)});
			write(8, std::uint32_t{0x45564157});
			write(12, std::uint32_t{0x20746D66});
			write(16, std::uint32_t{16});
			write(20, std::uint16_t{1});
			write(22, std::uint16_t{1});
			write(24, std::uint32_t{48000});
			write(28, std::uint32_t{96000});
			write(32, std::uint16_t{2});
			write(34, std::uint16_t{16});
			write(36, std::uint32_t{0x61746164});
			write(40, data_size);
			return bytes;
		}

		// Own one process initialization and engine for a contract test. An explicit config allows
		// individual tests to exercise small resource limits (e.g. max_streams) without waiting on
		// the default capacities.
		struct AudioFixture
		{
			AudioApi m_api;
			DllHandle m_context;
			EngineHandle m_engine;

			explicit AudioFixture(pr::audio::Config const* config = nullptr)
				: m_api()
				, m_context(m_api.Initialise(ReportErrorCB{{}, &SwallowError}))
				, m_engine()
			{
				PR_EXPECT(m_context != nullptr);
				PR_EXPECT(m_api.EngineCreate(m_context, config, &m_engine) == EStatus::Success);
			}
			~AudioFixture()
			{
				if (m_engine != 0)
					m_api.EngineDestroy(m_engine);
				if (m_context != nullptr)
					m_api.Shutdown(m_context);
			}
			AudioFixture(AudioFixture const&) = delete;
			AudioFixture& operator=(AudioFixture const&) = delete;
		};

